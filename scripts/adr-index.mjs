// Generates the index in docs/adr/README.md from each ADR's title and Status line.
// `node scripts/adr-index.mjs` rewrites it; scripts/check-doc-links.mjs fails when it is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const START = "<!-- adr-index:start (generated by scripts/adr-index.mjs; do not edit by hand) -->";
const END = "<!-- adr-index:end -->";
const STATUS = /^\s*(?:[-*]\s*)?(?:\*\*)?Status(?:\*\*)?:\s*/iu;
const LIMIT = 220;
// "X is superseded by", "later retired", "archived 2026-10-10": a part of this record, not another one.
const RETIRED_PART =
  /\b(?:is|are|was|were|later|half)\s+(?:\w+\s+)?(?:superseded|retired|archived)\b|\b(?:superseded|retired|archived)\s+(?:by|on|in|\(?\d{4})|\bsupersedes this\b/iu;

const title = (source, number) =>
  (/^#\s+(.+)$/mu.exec(source)?.[1] ?? "")
    .replace(new RegExp(`^(?:ADR\\s+)?${number}\\s*(?:[.:—-]\\s*)?`, "u"), "")
    .trim();

const status = (source) => {
  const lines = source.split("\n");
  const start = lines.findIndex((line) => STATUS.test(line));
  if (start === -1) return "No status line.";
  const paragraph = [lines[start].replace(STATUS, "")];
  for (const line of lines.slice(start + 1)) {
    if (!line.trim() || /^\s*[-*]\s|^#/u.test(line)) break;
    paragraph.push(line.trim());
  }
  const text = paragraph
    .join(" ")
    .replace(/\[([^\]]*)\]\((\d{4})-[^)]*\)/gu, (_, label, number) =>
      /\d{4}/u.test(label) ? label : `ADR ${number}`,
    )
    .replace(/\[([^\]]*)\]\([^)]*\)/gu, "$1")
    .replace(/\*\*/gu, "")
    .replace(/\s+/gu, " ")
    .trim();
  const sentence = /^(.+?[.!?])(?=\s|$)/u.exec(text)?.[1] ?? text;
  const clipped = sentence.length > LIMIT ? `${sentence.slice(0, LIMIT - 1).trimEnd()}…` : sentence;
  // A later sentence that retires part of the record still shows in the index.
  const partly =
    !/supersed|retire|archive/iu.test(clipped) && RETIRED_PART.test(text)
      ? " Partly superseded or retired; see its status."
      : "";
  return clipped.charAt(0).toUpperCase() + clipped.slice(1) + partly;
};

function adrIndex(root) {
  const directory = resolve(root, "docs/adr");
  const rows = readdirSync(directory)
    .filter((name) => /^\d{4}-.+\.md$/u.test(name))
    .sort()
    .map((name) => {
      const number = name.slice(0, 4);
      const source = readFileSync(resolve(directory, name), "utf8");
      return `- [${number}: ${title(source, number)}](${name}) — ${status(source)}`;
    });
  return [START, "", ...rows, "", END].join("\n");
}

/** Returns the README with its index regenerated, or throws when the markers are missing. */
export function withAdrIndex(root, readme) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end < start) throw new Error("docs/adr/README.md lacks the adr-index markers");
  return `${readme.slice(0, start)}${adrIndex(root)}${readme.slice(end + END.length)}`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = resolve(import.meta.dirname, "..");
  const path = resolve(root, "docs/adr/README.md");
  writeFileSync(path, withAdrIndex(root, readFileSync(path, "utf8")));
}
